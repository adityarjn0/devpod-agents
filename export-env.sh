#!/usr/bin/env bash
set -euo pipefail

umask 077

OUT_PATH="${1:-$HOME/.config/devpod/agents.env}"

python3 - "$OUT_PATH" <<'PY'
import base64
import json
import os
import shutil
import subprocess
import sys
import tempfile

out_path = os.path.expanduser(sys.argv[1])
out_dir = os.path.dirname(os.path.abspath(out_path))
os.makedirs(out_dir, mode=0o700, exist_ok=True)
os.chmod(out_dir, 0o700)

entries = []
MAX_LINE_BYTES = 60000  # Keep safe margin below DevPod ParseKeyValueFile 64 KiB scanner limit

def add_b64(key: str, raw_bytes: bytes):
    encoded = base64.b64encode(raw_bytes).decode("ascii")
    line = f"{key}={encoded}"
    if len(line.encode("utf-8")) >= MAX_LINE_BYTES:
        raise RuntimeError(
            f"{key} line length ({len(line)} bytes) exceeds safe limit ({MAX_LINE_BYTES} bytes)"
        )
    entries.append((key, line, len(raw_bytes)))

def read_json_file(path: str, validate=None) -> bytes:
    p = os.path.expanduser(path)
    if not os.path.isfile(p):
        raise FileNotFoundError(f"Missing required file: {p}")
    with open(p, "rb") as f:
        data = f.read()
    obj = json.loads(data.decode("utf-8"))
    if validate is not None:
        validate(obj, p)
    return data

# 1. Codex auth.json
def validate_codex(obj, p):
    if not isinstance(obj, dict) or ("tokens" not in obj and "OPENAI_API_KEY" not in obj):
        raise ValueError(f"Unexpected Codex auth schema in {p}")

add_b64("CODEX_AUTH_B64", read_json_file("~/.codex/auth.json", validate_codex))

# 2. Antigravity standalone OAuth token
def validate_agy_oauth(obj, p):
    if not isinstance(obj, dict) or not isinstance(obj.get("token"), dict) or not obj["token"].get("refresh_token"):
        raise ValueError(f"Missing token.refresh_token in {p}")

add_b64("AGY_OAUTH_B64", read_json_file("~/.gemini/jetski-standalone-oauth-token", validate_agy_oauth))

# 3. Antigravity CLI settings.json (sanitized for Linux containers)
agy_settings_path = os.path.expanduser("~/.gemini/antigravity-cli/settings.json")
if os.path.isfile(agy_settings_path):
    with open(agy_settings_path, "r", encoding="utf-8") as f:
        agy_settings = json.load(f)
    if not isinstance(agy_settings, dict):
        agy_settings = {}
    agy_settings["trustedWorkspaces"] = ["/workspaces"]
    add_b64(
        "AGY_SETTINGS_B64",
        (json.dumps(agy_settings, indent=2) + "\n").encode("utf-8"),
    )

# 4. OpenCode v2 stored credentials via `opencode auth export`
opencode_bin = os.path.expanduser("~/.opencode/bin/opencode")
if not os.path.isfile(opencode_bin) or not os.access(opencode_bin, os.X_OK):
    opencode_bin = shutil.which("opencode") or ""
if not opencode_bin:
    raise FileNotFoundError("Could not find opencode binary at ~/.opencode/bin/opencode or on PATH")

proc = subprocess.run(
    [opencode_bin, "auth", "export"],
    capture_output=True,
    check=True,
)
exported_raw = proc.stdout
exported_obj = json.loads(exported_raw.decode("utf-8"))
if not isinstance(exported_obj, list) or len(exported_obj) == 0:
    raise ValueError("`opencode auth export` returned empty or non-list JSON")
add_b64("OPENCODE_AUTH_B64", exported_raw)

# 5. OpenCode container-safe config files (allowlist only; no macOS symlinks or service.json)
for env_key, rel_path in [
    ("OPENCODE_JSONC_B64", "~/.config/opencode/opencode.jsonc"),
    ("OPENCODE_CLI_JSON_B64", "~/.config/opencode/cli.json"),
    ("OPENCODE_TUI_JSON_B64", "~/.config/opencode/tui.json"),
]:
    full_path = os.path.expanduser(rel_path)
    if os.path.isfile(full_path):
        with open(full_path, "rb") as f:
            add_b64(env_key, f.read())

fd, tmp_path = tempfile.mkstemp(prefix=".agents.env.", dir=out_dir)
try:
    os.chmod(tmp_path, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as out_f:
        out_f.write("# Generated by devpod-agents/export-env.sh — DO NOT COMMIT\n")
        for _, line, _ in entries:
            out_f.write(line + "\n")
    os.replace(tmp_path, out_path)
    os.chmod(out_path, 0o600)
except Exception:
    if os.path.exists(tmp_path):
        os.unlink(tmp_path)
    raise

print(f"Wrote {out_path} (mode 0600) with {len(entries)} entries:")
for key, line, raw_len in entries:
    print(f"  - {key}: raw={raw_len}B, line={len(line)}B")
PY
